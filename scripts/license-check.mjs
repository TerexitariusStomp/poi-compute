#!/usr/bin/env node
/**
 * license-check.mjs — mechanical OSS license gate.
 *
 * Policy (mirrors docs/oss-inventory + the repo's licensing decision):
 *   ALLOWED  — permissive (MIT/BSD/ISC/Apache/0BSD/Zlib/CC0/Unlicense/
 *              Python-2.0/WTFPL) and copyleft (MPL/LGPL/GPL/AGPL/EPL) —
 *              the repo itself is AGPL-3.0, copyleft is accepted provided
 *              commercial use is permitted.
 *   DENIED   — anything non-commercial, no-derivatives, or
 *              source-available: SSPL, BSL, Elastic, CC-*-NC/ND, Commons
 *              Clause, "LicenseRef-*", proprietary, unknown/missing.
 *
 * Every installed dependency must carry an SPDX id on the allow list —
 * unknowns fail loudly rather than slipping through. Exceptions go in
 * EXCEPTIONS below with a written justification + review date.
 *
 * Usage: node scripts/license-check.mjs          # gate (CI)
 *        node scripts/license-check.mjs --md     # regenerate docs/LICENSES.md
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

const ALLOWED = new Set([
  'MIT', 'MIT-0', 'ISC', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause',
  '0BSD', 'CC0-1.0', 'Zlib', 'Unlicense', 'Python-2.0', 'WTFPL',
  'MPL-2.0', 'LGPL-2.1', 'LGPL-3.0', 'GPL-3.0', 'AGPL-3.0',
  'EPL-1.0', 'EPL-2.0', 'CC-BY-4.0', 'OFL-1.1', 'BSD-3-Clause-Clear',
  'BlueOak-1.0.0', 'MIT-CMU', 'OLDAP-2.8', 'Unicode-DFS-2016',
  'Unicode-3.0', 'PostgreSQL', 'NCSA', 'Artistic-2.0', 'MulanPSL-2.0',
])

const DENIED = [
  /SSPL/i, /BSL/i, /Business.?Source/i, /Elastic/i, /Commons.?Clause/i,
  /CC-BY-NC/i, /CC-BY-ND/i, /CC-BY-SA/i, /NonCommercial/i, /NoDerivatives/i,
  /LicenseRef/i, /Proprietary/i, /UNLICENSED/i, /SEE LICENSE/i, /unknown/i,
]

/** Hard-won exceptions — each needs a reason and a re-review date. */
const EXCEPTIONS = {
  // 'pkg@ver': { reason: '...', until: 'YYYY-MM-DD' },
}

function normalize(id) {
  // "MPL 2.0" → "MPL-2.0", "LGPL-3.0-or-later" → "LGPL-3.0" — same grant.
  return id.trim()
    .replace(/^([A-Z]+)\s+(\d)/, '$1-$2')
    .replace(/-(only|or-later)$/i, '')
}

function licenseOk(license) {
  if (!license) return false
  const id = normalize(license)
  if (DENIED.some((re) => re.test(id))) return false
  if (ALLOWED.has(id)) return true
  // Composite SPDX — every term must be allowed (dual-license "OR" only
  // needs one allowed term).
  if (/\(|\)|\s(AND|OR|and|or)\s/.test(id)) {
    const orGroups = id.replace(/[()]/g, ' ').split(/\s+OR\s+|\s+or\s+/)
    return orGroups.some((group) =>
      group.split(/\s+AND\s+|\s+and\s+/).every((term) => ALLOWED.has(term.trim())))
  }
  return false
}

const raw = execFileSync('pnpm', ['licenses', 'list', '--json'], {
  cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024,
})
const byLicense = JSON.parse(raw)

const failures = []
const rows = []
for (const [license, pkgs] of Object.entries(byLicense)) {
  for (const p of pkgs) {
    const key = `${p.name}@${p.versions.join(',')}`
    const exception = EXCEPTIONS[key]
    const ok = licenseOk(license) || !!exception
    rows.push({ name: p.name, versions: p.versions.join(', '), license: license || '(missing)', ok, exception })
    if (!ok) failures.push({ name: p.name, license, versions: p.versions })
  }
}

if (process.argv.includes('--md')) {
  const grouped = {}
  for (const r of rows) (grouped[r.license] ??= []).push(r)
  const md = [
    '# Dependency Licenses',
    '',
    `Generated by \`scripts/license-check.mjs --md\` — ${new Date().toISOString().slice(0, 10)}.`,
    `Policy: permissive + copyleft allowed; non-commercial / source-available denied.`,
    '',
    ...Object.keys(grouped).sort().flatMap((lic) => [
      `## ${lic}`,
      '',
      ...grouped[lic].sort((a, b) => a.name.localeCompare(b.name))
        .map((r) => `- ${r.name} ${r.versions}`),
      '',
    ]),
  ].join('\n')
  writeFileSync(join(ROOT, 'docs/LICENSES.md'), md)
  console.log(`wrote docs/LICENSES.md (${rows.length} packages)`)
}

const bad = rows.filter((r) => !r.ok)
if (bad.length) {
  console.error(`\nLicense gate: ${bad.length} package(s) not on the allow list:`)
  for (const f of bad) console.error(`  ✗ ${f.name}@${f.versions} — ${f.license}`)
  process.exit(1)
}
console.log(`License gate: ${rows.length} packages OK (${new Set(rows.map(r => r.license)).size} distinct licenses)`)
